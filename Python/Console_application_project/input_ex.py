x = int(input("Enter first number: "))
y = int(input("Enter second number: "))

def add_numbers():  
    return x + y
def subtract_numbers():
    return x - y
def multiply_numbers():
    
    return x * y
def divide_numbers():
    
    if y != 0:
        return x / y
    else:
        return "Error! Division by zero."
